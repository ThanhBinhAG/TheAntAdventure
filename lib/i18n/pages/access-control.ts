/** Các key hợp lệ, được TypeScript kiểm tra khi component gọi tac(). */
export type AccessControlKey = keyof typeof ACCESS_CONTROL.en;

/** Lấy bản dịch Access Control theo ngôn ngữ hiện tại của CRM. */
export function tac(key: AccessControlKey, language: AppLanguage): string {
    return ACCESS_CONTROL[language][key] ?? ACCESS_CONTROL.en[key];
}

/** Nội suy giá trị động vào bản dịch, ví dụ số quyền hoặc tên role. */
export function tacTemplate(
    key: AccessControlKey,
    language: AppLanguage,
    values: Record<string, string | number>,
): string {
    return Object.entries(values).reduce(
        (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
        tac(key, language),
    );
}

