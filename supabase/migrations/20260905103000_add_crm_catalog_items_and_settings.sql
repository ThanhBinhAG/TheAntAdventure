-- CRM unified lookup catalogs + Settings permissions
-- Seeded from former client-side constants (countries, nationalities, sources, …).

create table if not exists public.crm_catalog_items (
  kind text not null check (kind ~ '^[a-z][a-z0-9_]{0,39}$'),
  code text not null check (code ~ '^[a-z0-9][a-z0-9-]{0,79}$'),
  label text not null check (length(trim(label)) between 1 and 120),
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (kind, code)
);

create unique index if not exists crm_catalog_items_kind_label_unique
  on public.crm_catalog_items (kind, lower(label));

create index if not exists crm_catalog_items_kind_active_sort
  on public.crm_catalog_items (kind, is_active, sort_order, label);

