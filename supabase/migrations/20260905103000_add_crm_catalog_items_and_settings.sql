alter table public.crm_catalog_items enable row level security;
revoke all on table public.crm_catalog_items from anon, authenticated;
grant select, insert, update, delete on table public.crm_catalog_items to authenticated;

drop policy if exists rls_crm_catalog_items_select on public.crm_catalog_items;
drop policy if exists rls_crm_catalog_items_insert on public.crm_catalog_items;
drop policy if exists rls_crm_catalog_items_update on public.crm_catalog_items;
drop policy if exists rls_crm_catalog_items_delete on public.crm_catalog_items;

create policy rls_crm_catalog_items_select on public.crm_catalog_items
  for select to authenticated using (
    public.has_permission('settings.read')
    or public.has_permission('customers.read')
    or public.has_permission('customers.write')
    or public.has_permission('tour_design.read')
  );

create policy rls_crm_catalog_items_insert on public.crm_catalog_items
  for insert to authenticated with check (public.has_permission('settings.write'));

create policy rls_crm_catalog_items_update on public.crm_catalog_items
  for update to authenticated
  using (public.has_permission('settings.write'))
  with check (public.has_permission('settings.write'));

create policy rls_crm_catalog_items_delete on public.crm_catalog_items
  for delete to authenticated using (public.has_permission('settings.write'));
